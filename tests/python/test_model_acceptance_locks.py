"""真實模型驗收與 CI real-sdk job 用的鎖定檔（#162）：.github/model-acceptance/<平臺>-requirements.{in,txt}。

.in 是 pip-compile 的輸入，套件行與使用者面向的 skills/<平臺>/requirements.txt 相同（dependabot 只動 .github/ 底下）；
.txt 由 pip-compile --generate-hashes 在 Python 3.12 下產生：每個套件都是 == 加 --hash，檔頭寫明 Python 3.12
（dependabot 依檔頭選 Python 版本重新編譯，要和 model-acceptance.yml 一致）。
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCK_DIR = ROOT / ".github" / "model-acceptance"
PLATFORMS = ["chatgpt", "deepseek", "gemini", "glm", "grok"]


def requirement_lines(path):
    """去掉註解與空行後的套件行（行尾註解也去掉）。"""
    lines = (line.split("#", 1)[0].strip() for line in path.read_text(encoding="utf-8").splitlines())
    return [line for line in lines if line]


def normalize(name):
    """套件名稱的比對形式：小寫，連續的 - _ . 視為一個 -（PEP 503）。"""
    return re.sub(r"[-_.]+", "-", name.lower())


def pinned(lock_text):
    """鎖定檔裡的 {套件名稱（normalize 過）: (版本, 雜湊數)}。"""
    result = {}
    for block in re.split(r"\n(?=\S)", lock_text):
        m = re.match(r"([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s;\\]+)", block)
        if m:
            result[normalize(m.group(1))] = (m.group(2), len(re.findall(r"--hash=sha256:[0-9a-f]{64}", block)))
    return result


class ModelAcceptanceLockTest(unittest.TestCase):
    def test_input_lists_the_same_requirements_as_the_user_facing_file(self):
        for platform in PLATFORMS:
            with self.subTest(platform=platform):
                self.assertEqual(requirement_lines(LOCK_DIR / f"{platform}-requirements.in"),
                                 requirement_lines(ROOT / "skills" / platform / "requirements.txt"))

    def test_lock_is_compiled_for_python_3_12_with_hashes(self):
        for platform in PLATFORMS:
            with self.subTest(platform=platform):
                text = (LOCK_DIR / f"{platform}-requirements.txt").read_text(encoding="utf-8")
                self.assertRegex(text, r"(?m)^# This file is autogenerated by pip-compile with Python 3\.12$")
                self.assertIn(f"pip-compile --generate-hashes --output-file={platform}-requirements.txt {platform}-requirements.in", text)
                packages = pinned(text)
                self.assertTrue(packages)
                unhashed = [name for name, (_, hashes) in packages.items() if hashes == 0]
                self.assertEqual(unhashed, [])
                # 每個套件區塊都是 == 鎖定：沒有 >=、~= 等範圍（--require-hashes 也要求這點）
                self.assertNotRegex(text, r"(?m)^[A-Za-z0-9][^\s#]*(>=|<=|~=|!=|>|<)")

    def test_every_direct_requirement_is_pinned(self):
        for platform in PLATFORMS:
            with self.subTest(platform=platform):
                packages = pinned((LOCK_DIR / f"{platform}-requirements.txt").read_text(encoding="utf-8"))
                for line in requirement_lines(LOCK_DIR / f"{platform}-requirements.in"):
                    name = normalize(re.match(r"[A-Za-z0-9._-]+", line).group(0))
                    self.assertIn(name, packages, line)


if __name__ == "__main__":
    unittest.main()
